function yearFromPeriod(periodLabel: string): number | undefined {
  const years = periodLabel.match(/\d{4}/g)?.map(Number);
  return years?.[years.length - 1];
}

function sortDateFromPeriod(periodLabel: string): string | undefined {
  const year = yearFromPeriod(periodLabel);
  return year ? `${year}-12-01` : undefined;
}

